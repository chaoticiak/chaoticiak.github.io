/* Attach anchor links to an element

The element will get:
- A "top" link pointing to topDestination
  - Unless the element is .no-top-link
  - topDestination is by default #title
  - (If topDestination is changed to an element/header, usually that element doesn't want "top" link, just "self")
- A "chain/self" link pointing to itself
  - Unless the element doesn't have any ID or is .no-self-link

Notes:
- Links are generated by an event listener, it's at the bottom of the script
- The generated links are part of the headers, inserted before the header text
- The generated links are .anchor, stylesheet should give a margin-right
- In logic.html, headings also get checkboxes (to mark what has been solved)
  The script for that is in logic.html itself, and is executed before this
  (If I want the checkboxes to be used more generally, I should be able to move it here)
*/

var topDestination = "title";

function addAnchors(el) {
    var newText = "";
    
    // Order is swapped because the first insert ends up being the right-most
    
    /* Chain/self */
    if (el.id && !el.classList.contains("no-self-link")) {
        var elChain = document.createElement("a");
        elChain.setAttribute("href", "#" + el.id);
        elChain.setAttribute("class", "anchor");
        elChain.innerHTML = "&#x1F517;";
        el.insertAdjacentElement("afterbegin", elChain);
    }
    
    /* Top */
    if (!el.classList.contains("no-top-link")) {
        var elTop = document.createElement("a");
        elTop.setAttribute("href", "#" + topDestination);
        elTop.setAttribute("class", "anchor");
        elTop.innerHTML = "&#x1F51D;";
        el.insertAdjacentElement("afterbegin", elTop);
    }
}



/* Remember checkbox/details state

Checkbox:
- Applies to elements with .remember-checkbox
- Stores state in localStorage as "check-" + ID
- The ID must be unique globally over the entire website

Details:
- Applies to elements with .remember-details
- Stores state in localStorage as "details-" + ID
- The ID must be unique globally over the entire website
*/
function checkboxStorageName(el) {
    return (el.id.slice(0,6) == "check-") ? el.id : "check-" + el.id;
}
function rememberCheckbox(e) {
    const el = e.target;
    if (el.checked) {
        localStorage.setItem(checkboxStorageName(el), "yes");
    } else {
        localStorage.removeItem(checkboxStorageName(el));
    }
}

function detailsStorageName(el) {
    return (el.id.slice(0,7) == "opened-") ? el.id : "opened-" + el.id;
}
function rememberDetails(e) {
    const el = e.target;
    if (el.open) {
        localStorage.setItem(detailsStorageName(el), "yes");
    } else {
        localStorage.removeItem(detailsStorageName(el));
    }
}



/* Wait until the page is loaded, then do the following:
- Add anchors to every h2, h3
  - h1 is only #title
  - h4 is usually too small to want its own link
- Every checkbox/details that want to be remembered *and have ID*:
  - Load its state
  - Attach listener to the toggle
- Hide .no-js content and show .yes-js content (likely useless)
*/
document.addEventListener("DOMContentLoaded", () => {
    for (el of document.querySelectorAll("h2, h3")) {
        addAnchors(el);
    }
    for (el of document.querySelectorAll("[id].remember-checkbox")) {
        if (localStorage.getItem(checkboxStorageName(el))) {el.setAttribute("checked", "");}
        el.addEventListener("change", rememberCheckbox);
    }
    for (el of document.querySelectorAll("[id].remember-details")) {
        if (localStorage.getItem(detailsStorageName(el))) {el.setAttribute("open", "");}
        el.addEventListener("toggle", rememberDetails);
    }
    for (el of document.querySelectorAll(".no-js")) {
        el.style.display = "none";
    }
    for (el of document.querySelectorAll(".yes-js")) {
        el.style.display = "block";
    }
});
